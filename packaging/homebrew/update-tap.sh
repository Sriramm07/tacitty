#!/bin/sh
# Regenerate the Homebrew formula for a published release.
#
#   sh packaging/homebrew/update-tap.sh v0.1.0 /path/to/homebrew-tap
#
# Downloads the release's .sha256 files (HTTPS only), writes
# Formula/tacitty.rb in the given checkout of github.com/Sriramm07/homebrew-tap,
# and leaves committing and pushing to you.
set -eu

tag="${1:?usage: update-tap.sh <tag, e.g. v0.1.0> <homebrew-tap checkout>}"
tap="${2:?usage: update-tap.sh <tag> <homebrew-tap checkout>}"
version="${tag#v}"
base="https://github.com/Sriramm07/tacitty/releases/download/$tag"

sum() {
    s="$(curl --proto '=https' --proto-redir '=https' -fsSL "$base/tacitty-$tag-$1.tar.gz.sha256" | cut -d' ' -f1)"
    case "$s" in
        [0-9a-f]*) [ "${#s}" -eq 64 ] && printf '%s' "$s" && return ;;
    esac
    echo "bad or missing checksum for $1" >&2
    exit 1
}

mac_arm="$(sum aarch64-apple-darwin)"
mac_intel="$(sum x86_64-apple-darwin)"
linux_arm="$(sum aarch64-unknown-linux-musl)"
linux_intel="$(sum x86_64-unknown-linux-musl)"

mkdir -p "$tap/Formula"
cat > "$tap/Formula/tacitty.rb" <<RUBY
# Generated by packaging/homebrew/update-tap.sh in github.com/Sriramm07/tacitty.
class Tacitty < Formula
  desc "Type @alias at any terminal password prompt and the real secret is sent instead"
  homepage "https://github.com/Sriramm07/tacitty"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/tacitty-$tag-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/tacitty-$tag-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/tacitty-$tag-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/tacitty-$tag-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "tacitty"
    doc.install "README.md"
    # The release tarball also ships a man page and shell completions
    # (generated from the CLI at build time); install them if present.
    man1.install "tacitty.1" if File.exist?("tacitty.1")
    bash_completion.install "completions/tacitty.bash" if File.exist?("completions/tacitty.bash")
    zsh_completion.install "completions/_tacitty" if File.exist?("completions/_tacitty")
    fish_completion.install "completions/tacitty.fish" if File.exist?("completions/tacitty.fish")
  end

  def caveats
    <<~EOS
      Run \`tacitty init\` to create your vault and turn on taciTTY for every
      new terminal (\`tacitty disable\` turns that off again).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tacitty --version")
  end
end
RUBY
echo "Wrote $tap/Formula/tacitty.rb for $tag"
